/**
 * Convert a page.tsx file path to its route path.
 * e.g. "app/(chef)/events/[id]/page.tsx" -> "/events/[id]"
 */
export function pageFileToRoute(filePath: string): string {
  // Normalize separators
  let route = filePath.replace(/\\/g, '/')

  // Strip "app/" prefix
  route = route.replace(/^app\//, '')

  // Strip trailing "/page.tsx" or just "page.tsx"
  route = route.replace(/\/?page\.tsx$/, '')

  // Strip route groups like (chef), (public), (admin), etc.
  route = route.replace(/\([^)]+\)\/?/g, '')

  // Trim trailing slash
  route = route.replace(/\/$/, '')

  // If empty (root page.tsx), return "/"
  if (!route) return '/'

  // Ensure leading slash
  return '/' + route
}

