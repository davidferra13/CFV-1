/** Total cuisine count */
export const CUISINE_COUNT = CUISINE_TYPES.length

/** Slug -> CuisineEntry lookup */
export const CUISINE_BY_SLUG: ReadonlyMap<string, CuisineEntry> = new Map(
  CUISINE_TYPES.map((c) => [c.slug, c])
)

/** Slug -> display name */
export const CUISINE_DISPLAY_MAP: Record<string, string> = Object.fromEntries(
  CUISINE_TYPES.map((c) => [c.slug, c.name])
)

function normalizeCuisineToken(value: string | null | undefined): string {
  return (value ?? '')
    .trim()
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
}

const CUISINE_CANONICAL_SLUG_BY_TOKEN: ReadonlyMap<string, string> = new Map([
  ...CUISINE_TYPES.flatMap((cuisine) => {
    const tokens = new Set([
      normalizeCuisineToken(cuisine.slug),
      normalizeCuisineToken(cuisine.name),
      normalizeCuisineToken(cuisine.name.replace(/\s*\/\s*/g, ' ')),
    ])

    return [...tokens].filter(Boolean).map((token) => [token, cuisine.slug] as const)
  }),
  ['bbq', 'barbecue'],
  ['barbeque', 'barbecue'],
  ['latin', 'latin_american'],
  ['middle_east', 'middle_eastern'],
  ['pastry', 'bakery'],
  ['pastries', 'bakery'],
  ['pastry_baking', 'bakery'],
  ['pastry_and_baking', 'bakery'],
  ['dessert', 'bakery'],
  ['desserts', 'bakery'],
  ['desserts_and_pastry', 'bakery'],
])

export function canonicalizeCuisineSlug(value: string | null | undefined): string | null {
  const token = normalizeCuisineToken(value)
  if (!token) return null

  return CUISINE_CANONICAL_SLUG_BY_TOKEN.get(token) ?? null
}

export function getCuisineEntry(value: string | null | undefined): CuisineEntry | null {
  const slug = canonicalizeCuisineSlug(value)
  return slug ? (CUISINE_BY_SLUG.get(slug) ?? null) : null
}

/** Get display name for a slug, fallback to titlecase */
export function getCuisineDisplayName(slug: string): string {
  const canonical = canonicalizeCuisineSlug(slug)
  if (canonical) return CUISINE_DISPLAY_MAP[canonical]

  return (
    CUISINE_DISPLAY_MAP[slug] ?? slug.replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase())
  )
}

export function getCuisineDisplayNames(values: readonly string[]): string[] {
  return values.map(getCuisineDisplayName)
}

/** Top N cuisines by popularity (for dropdowns, filters) */
export function getTopCuisines(n: number): readonly CuisineEntry[] {
  return [...CUISINE_TYPES].sort((a, b) => b.popularity - a.popularity).slice(0, n)
}

/** Cuisines filtered by region */
export function getCuisinesByRegion(region: CuisineRegion): readonly CuisineEntry[] {
  return CUISINE_TYPES.filter((c) => c.region === region)
}

/** Get children of a parent cuisine */
export function getChildCuisines(parentSlug: string): readonly CuisineEntry[] {
  const parent = canonicalizeCuisineSlug(parentSlug)
  if (!parent) return []

  return CUISINE_TYPES.filter((c) => c.parent === parent)
}

export function getCuisineAncestors(value: string): readonly CuisineEntry[] {
  const ancestors: CuisineEntry[] = []
  let cursor = getCuisineEntry(value)
  const visited = new Set<string>()

  while (cursor?.parent && !visited.has(cursor.parent)) {
    visited.add(cursor.parent)
    const parent = CUISINE_BY_SLUG.get(cursor.parent)
    if (!parent) break

    ancestors.push(parent)
    cursor = parent
  }

  return ancestors
}

export function getCuisineDescendants(value: string): readonly CuisineEntry[] {
  const root = canonicalizeCuisineSlug(value)
  if (!root) return []

  const descendants: CuisineEntry[] = []
  const queue = [root]
  const visited = new Set<string>()

  while (queue.length > 0) {
    const parent = queue.shift()
    if (!parent || visited.has(parent)) continue
    visited.add(parent)

    for (const child of getChildCuisines(parent)) {
      descendants.push(child)
      queue.push(child.slug)
    }
  }

  return descendants
}

