/** For select/combobox UIs: { value, label } sorted by popularity */
export function getCuisineOptions(opts?: {
  minPopularity?: number
  maxPopularity?: number
  region?: CuisineRegion
  limit?: number
  excludeOther?: boolean
}): readonly CuisineOption[] {
  let filtered = [...CUISINE_TYPES] as CuisineEntry[]
  if (opts?.minPopularity !== undefined) {
    filtered = filtered.filter((c) => c.popularity >= opts.minPopularity!)
  }
  if (opts?.maxPopularity !== undefined) {
    filtered = filtered.filter((c) => c.popularity <= opts.maxPopularity!)
  }
  if (opts?.region) {
    filtered = filtered.filter((c) => c.region === opts.region)
  }
  if (opts?.excludeOther) {
    filtered = filtered.filter((c) => c.slug !== 'other')
  }
  filtered.sort((a, b) => b.popularity - a.popularity)
  if (opts?.limit) {
    filtered = filtered.slice(0, opts.limit)
  }
  return filtered.map((c) => ({
    value: c.slug,
    label: c.name,
    region: c.region,
    subregion: c.subregion,
    popularity: c.popularity,
    tier: getCuisinePopularityTier(c.popularity),
    parent: c.parent,
  }))
}

export function getCuisineOptionsByRegion(opts?: {
  minPopularity?: number
  maxPopularity?: number
  limitPerRegion?: number
  excludeOther?: boolean
}): Record<CuisineRegion, readonly CuisineOption[]> {
  return Object.fromEntries(
    CUISINE_REGIONS.map((region) => {
      const options = getCuisineOptions({
        minPopularity: opts?.minPopularity,
        maxPopularity: opts?.maxPopularity,
        region,
        limit: opts?.limitPerRegion,
        excludeOther: opts?.excludeOther,
      })

      return [region, options]
    })
  ) as Record<CuisineRegion, readonly CuisineOption[]>
}

export function normalizeCuisineList(
  values: readonly string[] | null | undefined,
  opts?: {
    max?: number
    includeAncestors?: boolean
    includeDescendants?: boolean
    allowCustom?: boolean
  }
): string[] {
  const result: string[] = []
  const seen = new Set<string>()

  for (const value of values ?? []) {
    const canonical = canonicalizeCuisineSlug(value)
    const normalizedCustom = opts?.allowCustom ? normalizeCuisineToken(value) : null
    const slug = canonical ?? normalizedCustom

    if (!slug || seen.has(slug)) continue

    seen.add(slug)
    result.push(slug)

    if (canonical && opts?.includeAncestors) {
      for (const ancestor of getCuisineAncestors(canonical)) {
        if (!seen.has(ancestor.slug)) {
          seen.add(ancestor.slug)
          result.push(ancestor.slug)
        }
      }
    }

    if (canonical && opts?.includeDescendants) {
      for (const descendant of getCuisineDescendants(canonical)) {
        if (!seen.has(descendant.slug)) {
          seen.add(descendant.slug)
          result.push(descendant.slug)
        }
      }
    }

    if (opts?.max && result.length >= opts.max) {
      return result.slice(0, opts.max)
    }
  }

  return opts?.max ? result.slice(0, opts.max) : result
}

/** Legacy CUISINE_DISPLAY format for backward compat with recipe-constants */
export function buildCuisineDisplayRecord(minPopularity = 60): Record<string, string> {
  return Object.fromEntries(
    [...CUISINE_TYPES]
      .filter((c) => c.popularity >= minPopularity)
      .sort((a, b) => b.popularity - a.popularity)
      .map((c) => [c.slug, c.name])
  )
}
