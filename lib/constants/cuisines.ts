// Master Cuisine Type Registry
// Single source of truth for all cuisine types across ChefFlow.
// Ordered by global popularity (score 1-100). Every consumer derives from this list.
//
// Structure: hierarchical with regions, subregions, and parent cuisines.
// The DB enum (recipeCuisine) stays small; free-text fields reference slugs from this list.
// Popularity scores: research-backed (May 2026), sourced from restaurant density,
// search volume, cookbook publication, and international recognition data.

export type CuisineRegion =
  | 'Africa'
  | 'Americas'
  | 'Asia'
  | 'Europe'
  | 'Middle East'
  | 'Oceania'
  | 'Religious / Dietary'
  | 'Fusion / Commercial'

export type CuisineEntry = {
  slug: string
  name: string
  popularity: number // 1-100, higher = more popular globally
  region: CuisineRegion
  subregion: string
  parent: string | null // slug of parent cuisine, null for top-level
}

export type CuisinePopularityTier = 1 | 2 | 3 | 4 | 5 | 6 | 7

export type CuisineOption = {
  value: string
  label: string
  region: CuisineRegion
  subregion: string
  popularity: number
  tier: CuisinePopularityTier
  parent: string | null
}

export const CUISINE_POPULARITY_TIERS = [
  { tier: 1, label: 'Global giants', min: 90, max: 100 },
  { tier: 2, label: 'Major international', min: 75, max: 89 },
  { tier: 3, label: 'Strong regional / rising global', min: 60, max: 74 },
  { tier: 4, label: 'Established regional', min: 45, max: 59 },
  { tier: 5, label: 'Notable / niche', min: 30, max: 44 },
  { tier: 6, label: 'Sub-regional / emerging', min: 15, max: 29 },
  { tier: 7, label: 'Rare / hyperlocal', min: 1, max: 14 },
] as const satisfies readonly {
  tier: CuisinePopularityTier
  label: string
  min: number
  max: number
}[]

export function getCuisinePopularityTier(popularity: number): CuisinePopularityTier {
  if (!Number.isInteger(popularity)) {
    throw new RangeError(`Cuisine popularity must be an integer: ${popularity}`)
  }

  const match = CUISINE_POPULARITY_TIERS.find(
    (tier) => popularity >= tier.min && popularity <= tier.max
  )

  if (!match) {
    throw new RangeError(`Cuisine popularity must be between 1 and 100: ${popularity}`)
  }

  return match.tier
}

