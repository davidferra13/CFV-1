/* ------------------------------------------------------------------ helpers */

function walk(dir, base = '') {
  const out = []
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const rel = base ? `${base}/${entry.name}` : entry.name
    const abs = path.join(dir, entry.name)
    if (entry.isDirectory()) out.push(...walk(abs, rel))
    else if (entry.isFile()) out.push({ rel, abs })
  }
  return out.sort((a, b) => a.rel.localeCompare(b.rel))
}

/** Reads PNG/JPEG/GIF/WebP/SVG dimensions without any image library. */
function dimensions(file) {
  let fd
  try {
    fd = fs.openSync(file, 'r')
    const buf = Buffer.alloc(65536)
    const read = fs.readSync(fd, buf, 0, 65536, 0)
    const b = buf.subarray(0, read)

    if (b.length > 24 && b.readUInt32BE(0) === 0x89504e47) {
      return { width: b.readUInt32BE(16), height: b.readUInt32BE(20) }
    }
    if (b[0] === 0xff && b[1] === 0xd8) {
      let i = 2
      while (i < b.length - 9) {
        if (b[i] !== 0xff) { i += 1; continue }
        const marker = b[i + 1]
        if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) {
          return { height: b.readUInt16BE(i + 5), width: b.readUInt16BE(i + 7) }
        }
        i += 2 + b.readUInt16BE(i + 2)
      }
      return null
    }
    if (b.subarray(0, 4).toString('ascii') === 'RIFF' && b.subarray(8, 12).toString('ascii') === 'WEBP') {
      const fmt = b.subarray(12, 16).toString('ascii')
      if (fmt === 'VP8X') return { width: 1 + b.readUIntLE(24, 3), height: 1 + b.readUIntLE(27, 3) }
      if (fmt === 'VP8 ') return { width: b.readUInt16LE(26) & 0x3fff, height: b.readUInt16LE(28) & 0x3fff }
      if (fmt === 'VP8L') {
        const bits = b.readUInt32LE(21)
        return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 }
      }
      return null
    }
    if (path.extname(file).toLowerCase() === '.svg') {
      const text = b.toString('utf8')
      const vb = text.match(/viewBox=["']\s*[-\d.]+\s+[-\d.]+\s+([\d.]+)\s+([\d.]+)/i)
      if (vb) return { width: Number(vb[1]), height: Number(vb[2]), from: 'viewBox' }
      const w = text.match(/\bwidth=["']([\d.]+)/i)
      const h = text.match(/\bheight=["']([\d.]+)/i)
      if (w && h) return { width: Number(w[1]), height: Number(h[1]) }
      return null
    }
    return null
  } catch {
    return null
  } finally {
    if (fd !== undefined) fs.closeSync(fd)
  }
}

function curatedFor(rel) {
  if (CURATED[rel]) return { ...CURATED[rel], curated: true }
  for (const { prefix, meta } of CURATED_PREFIXES) {
    if (rel.startsWith(prefix)) return { ...meta, curated: true }
  }
  return { status: 'unclassified', curated: false, notes: 'No curated entry. Classify it in build-asset-registry.mjs or remove the file.' }
}

/* -------------------------------------------------------------------- build */

/*
 * Text assets (SVG, JSON, plain text) are checked out with CRLF on Windows and
 * LF elsewhere, so their on-disk size differs by one byte per line between
 * clones of the same commit. Recording the raw size would make this registry
 * disagree with itself across platforms and keep `registry:check` red on
 * Windows forever. Size text assets from their normalised bytes; binaries are
 * read straight off disk.
 */
const TEXT_EXT = new Set([
  'svg',
  'json',
  'txt',
  'xml',
  'webmanifest',
  'md',
  'csv',
  'js',
  'mjs',
  'cjs',
  'css',
  'html',
  'htm',
  'map',
  'vtt',
  'srt',
  'yml',
  'yaml',
])

function assetBytes(abs, ext) {
  if (!TEXT_EXT.has(ext)) return fs.statSync(abs).size
  return Buffer.byteLength(fs.readFileSync(abs, 'utf8').replace(/\r\n/g, '\n'), 'utf8')
}

const files = walk(PUBLIC_DIR)
const bySize = new Map()
const assets = files.map((f) => {
  const dim = dimensions(f.abs)
  const ext = path.extname(f.rel).slice(1).toLowerCase()
  const size = assetBytes(f.abs, ext)
  const key = `${size}`
  bySize.set(key, [...(bySize.get(key) ?? []), f.rel])
  return {
    path: `public/${f.rel}`,
    url: `/${f.rel}`,
    ext,
    bytes: size,
    ...(dim ? { width: dim.width, height: dim.height } : {}),
    ...curatedFor(f.rel),
  }
})

// Same-byte-size groups are surfaced as likely duplicates, never auto-removed.
const duplicateGroups = [...bySize.entries()]
  .filter(([, list]) => list.length > 1)
  .map(([size, list]) => ({ bytes: Number(size), files: list.map((p) => `public/${p}`) }))

// A PNG that has a WebP sibling is a shipping-weight finding.
const webp = new Set(assets.filter((a) => a.ext === 'webp').map((a) => a.path.replace(/\.webp$/, '')))
