/*
 * lint-staged runs prettier on every staged file, so unformatted output here
 * would make --check permanently stale. Format with the project's own config so
 * the generated file and the committed file agree by construction.
 */
let next = JSON.stringify(registry, null, 2) + '\n'
try {
  const prettier = await import('prettier')
  const config = (await prettier.resolveConfig(OUT)) ?? {}
  next = await prettier.format(next, { ...config, filepath: OUT })
} catch {
  // Prettier missing: emit plain JSON. The generator still works.
}
const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null

/*
 * Line endings are a checkout detail, not an asset change. Git on Windows checks
 * this file out with CRLF while the generator emits LF, so a byte comparison
 * reports it stale on a Windows clone even when public/ has not moved. Compare
 * on normalised text and keep the file's existing convention when writing.
 */
const normaliseEol = (text) => text.replace(/\r\n/g, '\n')

if (checkOnly) {
  if (prev === null || normaliseEol(prev) !== normaliseEol(next)) {
    console.error('STALE  design-system/registry/assets.json - run: npm run registry:build')
    // Say what moved. "STALE" on its own sends the next agent hunting; the
    // usual causes are an asset added or removed, or a text asset whose
    // extension is missing from TEXT_EXT above so its size is being read
    // with the checkout's line endings.
    try {
      const before = JSON.parse(prev ?? '{"assets":[]}')
      const beforeBy = new Map((before.assets ?? []).map((a) => [a.path, a]))
      const afterBy = new Map(assets.map((a) => [a.path, a]))
      for (const [p, a] of afterBy) {
        const b = beforeBy.get(p)
        if (!b) console.error(`  added    ${p}`)
        else if (b.bytes !== a.bytes) console.error(`  resized  ${p}  ${b.bytes} -> ${a.bytes}`)
      }
      for (const p of beforeBy.keys()) if (!afterBy.has(p)) console.error(`  removed  ${p}`)
    } catch {
      // Unparseable previous file: the plain STALE line is all we can offer.
    }
    process.exit(1)
  }
  console.log('ok     design-system/registry/assets.json')
} else {
  fs.writeFileSync(OUT, prev && prev.includes('\r\n') ? next.replace(/\n/g, '\r\n') : next)
  console.log(
    `wrote  design-system/registry/assets.json (${assets.length} assets, ${registry.meta.totals.unclassified} unclassified, ${duplicateGroups.length} duplicate byte groups)`
  )
}
